export const ONBOARDING_TRANSLATIONS: Record<OnboardingLocale, Catalog> = { de, en, es };

export const getOnboardingLocaleTag = (locale: OnboardingLocale) => ({
  de: 'de-DE',
  en: 'en-US',
  es: 'es-ES',
})[locale];

export const translateOnboardingText = (
  locale: OnboardingLocale,
  key: OnboardingTranslationKey,
  params: Record<string, string | number> = {},
) => {
  const template = ONBOARDING_TRANSLATIONS[locale]?.[key] ?? de[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) =>
    String(params[token] ?? `{{${token}}}`),
  );
};
