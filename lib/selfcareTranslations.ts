export const SELFCARE_TRANSLATIONS: Record<SelfcareLocale, Catalog> = { de, en, es };

export const getSelfcareLocaleTag = (locale: SelfcareLocale) => ({
  de: 'de-DE',
  en: 'en-US',
  es: 'es-ES',
})[locale];

export const translateSelfcareText = (
  locale: SelfcareLocale,
  key: SelfcareTranslationKey,
  params: Record<string, string | number> = {},
) => {
  const template = SELFCARE_TRANSLATIONS[locale]?.[key] ?? de[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) =>
    String(params[token] ?? `{{${token}}}`),
  );
};

export const SELFCARE_TIP_KEYS = Array.from(
  { length: 10 },
  (_, index) => `tip.${index + 1}` as SelfcareTranslationKey,
);

export const SELFCARE_EXERCISES = Array.from({ length: 4 }, (_, index) => ({
  titleKey: `exercise.${index + 1}.title` as SelfcareTranslationKey,
  descriptionKey: `exercise.${index + 1}.description` as SelfcareTranslationKey,
}));

export const SELFCARE_ACTIVITIES = Array.from({ length: 8 }, (_, index) => ({
  id: String(index + 1),
  titleKey: `activity.${index + 1}` as SelfcareTranslationKey,
}));
