export type PregnancyBriefingTranslationKey = keyof typeof PREGNANCY_BRIEFING_TRANSLATIONS.de;

export const translatePregnancyBriefingText = (
  locale: AppLocale,
  key: PregnancyBriefingTranslationKey,
  params?: Record<string, string | number>,
) => {
  let value: string = PREGNANCY_BRIEFING_TRANSLATIONS[locale][key];
  for (const [name, replacement] of Object.entries(params ?? {})) {
    value = value.replaceAll(`{{${name}}}`, String(replacement));
  }
  return value;
};
