import React from 'react';
import AsyncStorage from '@react-native-async-storage/async-storage';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { SleepOfflineProvider, useSleepOffline } from '@/contexts/SleepOfflineContext';
import { readSleepCapability, readSleepSyncSnapshot, type SleepScopeSnapshot, type VersionedSleepEntry } from '../sleepSyncContract';
import { writeSnapshot, readSnapshot } from '../localReadSnapshots';
import { rememberActiveSleep, createPendingSleepStop } from '../sleepOfflineActions';
import { sleepActivityService } from '../sleepActivityService';
import { clearSleepWidget } from '../sleepWidget';
let mockGeneration = 0;
const mockChannel = { on: jest.fn().mockReturnThis(), subscribe: jest.fn().mockReturnThis() };
jest.mock('../supabase', () => ({ supabaseUrl: 'https://fixture.supabase.co', supabase: { channel: () => mockChannel, removeChannel: jest.fn() } }));
jest.mock('../dataConsentRuntime', () => ({ getRuntimeDataConsents: () => ({ userId: 'a', generation: mockGeneration }), runtimeConsentAllowed: () => true, subscribeDataConsents: () => () => {} }));
jest.mock('@/contexts/AuthContext', () => ({ useAuth: () => ({ user: { id: 'a' } }) }));
jest.mock('@/contexts/ActiveBabyContext', () => ({ useActiveBaby: () => ({ activeBabyId: 'baby', babies: [{ id: 'baby', name: 'Fixture' }] }) }));
jest.mock('@/contexts/LocaleContext', () => ({ useLocale: () => ({ locale: 'de' }) }));
jest.mock('@/components/SleepSyncConflictModal', () => ({ SleepSyncConflictModal: () => null }));
jest.mock('../sleepSyncContract', () => ({ ...jest.requireActual('../sleepSyncContract'), SLEEP_OFFLINE_ENABLED: true, readSleepCapability: jest.fn(), readSleepSyncSnapshot: jest.fn() }));
jest.mock('../sleepOfflineRecovery', () => ({ runSleepRecovery: jest.fn(async () => {}), editPendingSleepStop: jest.fn() }));
jest.mock('../sleepActivityService', () => ({ sleepActivityService: { endSleepActivityById: jest.fn(async () => true), restoreCurrentActivity: jest.fn(async () => null), startSleepActivity: jest.fn(async () => 'new-native'), endAllSleepActivities: jest.fn(async () => true) } }));
jest.mock('../sleepWidget', () => ({ clearSleepWidget: jest.fn(async () => {}), syncSleepWidget: jest.fn(async () => {}) }));
jest.mock('../nightWindowSettings', () => ({ loadNightWindowSettings: jest.fn(async () => ({ startHour: 18, startMinute: 0, endHour: 10, endMinute: 0 })) }));
jest.mock('expo-crypto', () => ({ randomUUID: () => 'fixture-op' }));
const scope = { backendHost: 'fixture.supabase.co', userId: 'a', babyId: 'baby' };
const entry: VersionedSleepEntry = { id: 'original', user_id: 'a', baby_id: 'baby', start_time: new Date(Date.now() - 3600000).toISOString(), end_time: null, duration_minutes: null, notes: null, quality: null, partner_id: null, shared_with_user_id: null, updated_by: null, sync_revision: '1' };
const snapshot: SleepScopeSnapshot = { status: 'available', babyId: 'baby', scopeRevision: '1', entries: [entry], original: entry, canWrite: true, verifiedAt: new Date().toISOString() };
let value!: ReturnType<typeof useSleepOffline>; let tree: ReactTestRenderer | undefined;
function Probe() { const current = useSleepOffline(); React.useLayoutEffect(() => { value = current; }); return null; }
const mount = async () => { await act(async () => { tree = create(<SleepOfflineProvider><Probe /></SleepOfflineProvider>); }); };
const read = jest.mocked(readSleepSyncSnapshot);
beforeEach(async () => { mockGeneration++; await AsyncStorage.clear(); jest.clearAllMocks(); jest.mocked(readSleepCapability).mockResolvedValue(true); read.mockResolvedValue(snapshot); });
afterEach(async () => { await act(async () => { tree?.unmount(); }); tree = undefined; });
it.each(['scope', 'target'])('confirmed %s access loss clears cached payload without requiring a pending action', async step => {
  await writeSnapshot(scope, 'care', [{ id: 'private' }]); await rememberActiveSleep(scope, snapshot);
  read.mockResolvedValue({ status: 'forbidden' });
  if (step === 'target') read.mockResolvedValueOnce(snapshot);
  await mount();
  expect(value.knownActive).toBeNull(); expect(value.enabled).toBe(false);
  expect(await readSnapshot(scope, 'care', (v): v is any[] => Array.isArray(v))).toBeNull();
  expect(await readSnapshot(scope, 'sleep-active', (v): v is any => !!v)).toBeNull();
  expect(clearSleepWidget).toHaveBeenCalled();
  expect(read.mock.calls.length).toBeLessThanOrEqual(2);
});
it('cold start without network ends only the persisted binding for the locally stopped original', async () => {
  await writeSnapshot(scope, 'sleep-capability', true); await rememberActiveSleep(scope, snapshot);
  await writeSnapshot(scope, 'sleep-native-binding', { entryId: entry.id, activityId: 'bound-original-native' });
  await createPendingSleepStop(scope, { entry, scopeRevision: '1', verifiedAt: snapshot.verifiedAt, canWrite: true }, new Date().toISOString(), 'good', null);
  jest.mocked(readSleepCapability).mockRejectedValue(new Error('offline'));
  await mount();
  expect(sleepActivityService.endSleepActivityById).toHaveBeenCalledWith('bound-original-native', 'good', expect.any(String));
  expect(sleepActivityService.startSleepActivity).not.toHaveBeenCalled(); expect(sleepActivityService.endAllSleepActivities).not.toHaveBeenCalled();
  expect(clearSleepWidget).toHaveBeenCalled(); expect(value.actions[0]?.state).toBe('pending');
});
it('offline restoration never assumes an unbound current activity belongs to the original', async () => {
  await rememberActiveSleep(scope, snapshot);
  await createPendingSleepStop(scope, { entry, scopeRevision: '1', verifiedAt: snapshot.verifiedAt, canWrite: true }, new Date().toISOString(), 'good', null);
  jest.mocked(readSleepCapability).mockRejectedValue(new Error('offline'));
  await mount();
  expect(sleepActivityService.endSleepActivityById).not.toHaveBeenCalled(); expect(sleepActivityService.endAllSleepActivities).not.toHaveBeenCalled();
});
