export const RECIPE_TRANSLATIONS: Record<RecipeLocale, RecipeCatalog> = {
  de,
  en,
  es,
};

export const getRecipeLocaleTag = (locale: RecipeLocale) =>
  ({
    de: "de-DE",
    en: "en-US",
    es: "es-ES",
  })[locale];

export const translateRecipeText = (
  locale: RecipeLocale,
  key: RecipeTranslationKey,
  params?: Record<string, string | number>,
) => {
  const template = RECIPE_TRANSLATIONS[locale]?.[key] ?? de[key] ?? key;
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_match, name: string) =>
    params[name] !== undefined ? String(params[name]) : "",
  );
};

export const translateRecipePlural = (
  locale: RecipeLocale,
  key:
    | "hero.recipeCount"
    | "catalog.count"
    | "catalog.hidden"
    | "recipe.ingredients"
    | "age.months"
    | "age.fromLong",
  count: number,
) =>
  translateRecipeText(
    locale,
    `${key}.${count === 1 ? "one" : "other"}` as RecipeTranslationKey,
    { count },
  );

export const getRecipeAllergenLabel = (
  locale: RecipeLocale,
  allergen: string,
) =>
  `allergy.${allergen}` in RECIPE_TRANSLATIONS[locale]
    ? translateRecipeText(locale, `allergy.${allergen}` as RecipeTranslationKey)
    : allergen;
