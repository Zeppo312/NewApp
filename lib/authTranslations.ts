export const AUTH_TRANSLATIONS: Record<AuthLocale, Catalog> = { de, en, es };

export const getAuthLocaleTag = (locale: AuthLocale) => ({
  de: 'de-DE',
  en: 'en-US',
  es: 'es-ES',
})[locale];

export const translateAuthText = (
  locale: AuthLocale,
  key: AuthTranslationKey,
  params: Record<string, string | number> = {},
) => {
  const template = AUTH_TRANSLATIONS[locale]?.[key] ?? de[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) =>
    String(params[token] ?? `{{${token}}}`),
  );
};
