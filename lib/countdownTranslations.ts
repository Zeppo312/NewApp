export const localizeBirthPreparationMeasure = <T extends LocalizableBirthPreparationMeasure>(
  locale: CountdownLocale,
  measure: T,
): T => {
  if (locale === 'de') return measure;
  const localized = birthPreparationCopy[locale][measure.id];
  return localized ? { ...measure, ...localized } : measure;
};

export const getCountdownDayLabel = (locale: CountdownLocale, days: number, overdue = false) =>
  translateCountdownText(
    locale,
    overdue
      ? Math.abs(days) === 1 ? 'timer.daysOverdue.one' : 'timer.daysOverdue.other'
      : Math.abs(days) === 1 ? 'timer.days.one' : 'timer.days.other',
    { days: Math.abs(days) },
  );
