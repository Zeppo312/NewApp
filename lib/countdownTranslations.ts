export const COUNTDOWN_TRANSLATIONS: Record<CountdownLocale, Catalog> = { de, en, es };

export const getCountdownLocaleTag = (locale: CountdownLocale) => ({
  de: 'de-DE',
  en: 'en-US',
  es: 'es-ES',
})[locale];

export const translateCountdownText = (
  locale: CountdownLocale,
  key: CountdownTranslationKey,
  params: Record<string, string | number> = {},
) => {
  const template = COUNTDOWN_TRANSLATIONS[locale]?.[key] ?? de[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) => String(params[token] ?? `{{${token}}}`));
};

