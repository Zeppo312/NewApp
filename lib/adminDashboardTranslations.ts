const ADMIN_DASHBOARD_TRANSLATIONS: Record<AppLocale, Catalog> = { de, en, es };

export const translateAdminDashboardText = (
  locale: AppLocale,
  key: AdminDashboardTranslationKey,
  params: Record<string, string | number> = {},
) => {
  const template = ADMIN_DASHBOARD_TRANSLATIONS[locale]?.[key] ?? de[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) =>
    String(params[token] ?? `{{${token}}}`),
  );
};
