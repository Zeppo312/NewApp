export const BABY_WEATHER_TRANSLATIONS: Record<BabyWeatherLocale, Catalog> = { de, en, es };

export const translateBabyWeatherText = (
  locale: BabyWeatherLocale,
  key: BabyWeatherTranslationKey,
  params: Record<string, string | number> = {},
) => {
  const template = BABY_WEATHER_TRANSLATIONS[locale]?.[key] ?? de[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) => String(params[token] ?? `{{${token}}}`));
};

export const getBabyWeatherLocaleTag = (locale: BabyWeatherLocale) => ({
  de: 'de-DE',
  en: 'en-US',
  es: 'es-ES',
})[locale];

export const getBabyWeatherApiLanguage = (locale: BabyWeatherLocale) => locale;

export const getBabyWeatherContextLabel = (locale: BabyWeatherLocale, context: string) =>
  translateBabyWeatherText(locale, `context.${context}` as BabyWeatherTranslationKey);

export const getBabyWeatherClothingLabel = (locale: BabyWeatherLocale, clothingName: string) =>
  translateBabyWeatherText(locale, `clothing.${clothingName}` as BabyWeatherTranslationKey);

export const formatBabyWeatherMonths = (locale: BabyWeatherLocale, count: number) =>
  translateBabyWeatherText(locale, count === 1 ? 'info.month.one' : 'info.month.other', { count });

export const getBabyWeatherTipKeys = (band: string): BabyWeatherTranslationKey[] => {
  const counts: Record<string, number> = { hot: 5, warm: 3, mild: 3, cool: 3, fresh: 3, cold: 4 };
  return Array.from({ length: counts[band] ?? 0 }, (_, index) => `tip.${band}.${index + 1}` as BabyWeatherTranslationKey);
};
